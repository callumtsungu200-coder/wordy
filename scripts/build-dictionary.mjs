// Regenerates src/data/dictionary.ts from the an-array-of-english-words package.
// Run with: node scripts/build-dictionary.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const words = require('an-array-of-english-words');

const fiveLetter = [...new Set(words.filter((w) => /^[a-z]{5}$/.test(w)))].sort();

const out = `// Generated by scripts/build-dictionary.mjs — do not edit by hand.
// ${fiveLetter.length} five-letter words accepted as valid guesses.
export const DICTIONARY_RAW = '${fiveLetter.join(' ')}';
`;

writeFileSync(new URL('../src/data/dictionary.ts', import.meta.url), out);
console.log(`Wrote ${fiveLetter.length} words.`);
